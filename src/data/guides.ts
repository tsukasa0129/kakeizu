export function recommendRoute(answers: Record<string, string>): { guideId: string; reason: string } {
  if (answers.goal === 'self' && answers.myna === 'yes') {
    return { guideId: 'convenience', reason: 'マイナンバーカードがあれば、自分の戸籍はコンビニですぐ取れます。朝や夜でもOKです。' };
  }
  if (answers.visit === 'yes') {
    return {
      guideId: 'koiki',
      reason: '平日に役所へ行けるなら「広域交付」がおすすめ。近くの役所1か所で、親や祖父母の戸籍までまとめて取れます。',
    };
  }
  return { guideId: 'mail', reason: '役所に行くのが難しいなら、本籍地の役所に郵便で頼むのが確実です。家にいながら取れます。' };
}
